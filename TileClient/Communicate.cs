		/// </summary>
		string RequestTarget { get; }
		/// <summary>
		/// Gets or sets the payload data of the request.
		/// <para xml:lang="zh-Hans">获取或设置请求的负载数据。</para>
		/// <para xml:lang="zh-Hant">取得或設定要求的承載資料。</para>
		/// </summary>
		object RequestDatas { get; }
		/// <summary>
		/// Gets or sets auxiliary data used only by the tile itself; it is passed through unchanged.
		/// <para xml:lang="zh-Hans">获取或设置仅供磁贴自身使用的辅助数据；该数据会原样传递。</para>
		/// <para xml:lang="zh-Hant">取得或設定僅供磁貼自身使用的輔助資料；該資料會原樣傳遞。</para>
		/// </summary>
		object TransferDatas { get; }
	}
	/// <summary>
	/// Represents a request sent from a tile to another tile or to the Sidebar.
	/// <para xml:lang="zh-Hans">表示从磁贴发送到其他磁贴或边栏的请求。</para>
	/// <para xml:lang="zh-Hant">表示從磁貼傳送到其他磁貼或邊欄的要求。</para>
	/// </summary>
	[ComVisible (true)]
	public class TileRequest: ITileRequest
	{
		/// <summary>
		/// The UTC time when this request was created. Used to generate the request ID.
		/// <para xml:lang="zh-Hans">创建此请求时的 UTC 时间，用于生成请求 ID。</para>
		/// <para xml:lang="zh-Hant">建立此要求時的 UTC 時間，用於產生要求 ID。</para>
		/// </summary>
		private DateTime genTime = DateTime.UtcNow;
		/// <summary>
		/// Gets or sets the payload data of the request.
		/// <para xml:lang="zh-Hans">获取或设置请求的负载数据。</para>
		/// <para xml:lang="zh-Hant">取得或設定要求的承載資料。</para>
		/// </summary>
		public object RequestDatas { get; set; }
		/// <summary>
		/// Gets the unique identifier of the request. It is generated by hashing the request name, source, target, and creation time with SHA-256.
		/// <para xml:lang="zh-Hans">获取请求的唯一标识符。该标识符通过对请求名称、来源、目标和创建时间进行 SHA-256 哈希生成。</para>
		/// <para xml:lang="zh-Hant">取得要求的唯一識別碼。該識別碼透過對要求名稱、來源、目的地的建立時間進行 SHA-256 雜湊產生。</para>
		/// </summary>
		public string RequestId
		{
			get
			{
				string raw = $"{(RequestName ?? "").NNormalize ()}|{(RequestSource ?? "").NNormalize ()}|{(RequestTarget ?? "").NNormalize ()}|{genTime.Ticks}";
				using (var sha256 = SHA256.Create ())
				{
					byte [] hash = sha256.ComputeHash (Encoding.UTF8.GetBytes (raw));
					StringBuilder sb = new StringBuilder (32);
					for (int i = 0; i < 16; i++) sb.Append (hash [i].ToString ("x2"));
					return sb.ToString ();
				}
			}
		}
		/// <summary>
		/// Gets or sets the name of the request, which identifies the operation to perform.
		/// <para xml:lang="zh-Hans">获取或设置请求的名称，用于标识要执行的操作。</para>
		/// <para xml:lang="zh-Hant">取得或設定要求的名稱，用於識別要執行的作業。</para>
		/// </summary>
		public string RequestName { get; set; }
		/// <summary>
		/// Gets the user model ID of the tile that sent the request.
		/// <para xml:lang="zh-Hans">获取发送请求的磁贴的用户模型 ID。</para>
		/// <para xml:lang="zh-Hant">取得傳送要求的磁貼的使用者模型 ID。</para>
		/// </summary>
		public string RequestSource { get; }
		/// <summary>
		/// Gets or sets the target of the request, such as "Sidebar" or the user model ID of another tile.
		/// <para xml:lang="zh-Hans">获取或设置请求的目标，例如 "Sidebar" 或其他磁贴的用户模型 ID。</para>
		/// <para xml:lang="zh-Hant">取得或設定要求的目的地，例如 "Sidebar" 或其他磁貼的使用者模型 ID。</para>
		/// </summary>
		public string RequestTarget { get; set; }
		/// <summary>
		/// Gets or sets auxiliary data used only by the tile itself; it is passed through unchanged.
		/// <para xml:lang="zh-Hans">获取或设置仅供磁贴自身使用的辅助数据；该数据会原样传递。</para>
		/// <para xml:lang="zh-Hant">取得或設定僅供磁貼自身使用的輔助資料；該資料會原樣傳遞。</para>
		/// </summary>
		public object TransferDatas { get; set; }
		/// <summary>
		/// Initializes a new instance of the <see cref="TileRequest"/> class with the specified source tile.
		/// <para xml:lang="zh-Hans">使用指定的源磁贴初始化 <see cref="TileRequest"/> 类的新实例。</para>
		/// <para xml:lang="zh-Hant">使用指定的來源磁貼初始化 <see cref="TileRequest"/> 類別的新執行個體。</para>
		/// </summary>
		/// <param name="itb">The tile that sends the request. Its <see cref="ITileBase.UserModelId"/> is used as the request source.
		/// <para xml:lang="zh-Hans">发送请求的磁贴。其 <see cref="ITileBase.UserModelId"/> 将作为请求来源。</para>
		/// <para xml:lang="zh-Hant">傳送要求的磁貼。其 <see cref="ITileBase.UserModelId"/> 將作為要求來源。</para>
		/// </param>
		public TileRequest (ITileBase itb)
		{
			RequestSource = itb.UserModelId;
		}
	}
