	/// <summary>
	/// Defines the contract for a request sent between tiles or between a tile and the Sidebar.
	/// <para xml:lang="zh-Hans">定义磁贴之间或磁贴与边栏之间发送的请求的契约。</para>
	/// <para xml:lang="zh-Hant">定義磁貼之間或磁貼與邊欄之間傳送的要求的契約。</para>
