	/// <summary>
	/// Provides features for communicating with Sidebar and other tiles, including sending requests, communicating with specific targets, and sending responses.
	/// <para xml:lang="zh-Hans">提供与边栏和其他磁贴通信的功能，包括发送请求、与指定目标通信以及发送响应。</para>
	/// <para xml:lang="zh-Hant">提供與邊欄和其他磁貼通訊的功能，包括傳送要求、與指定目的地通訊以及傳送回應。</para>
	/// </summary>
	[ComVisible (true)]
	public interface ISidebarFeatures
	{
		/// <summary>
		/// Sends a request to the Sidebar.
		/// <para xml:lang="zh-Hans">向边栏发送请求。</para>
		/// <para xml:lang="zh-Hant">向邊欄傳送要求。</para>
		/// </summary>
		/// <param name="request">The request body, which must be an <see cref="ISidebarRequest"/>.
		/// <para xml:lang="zh-Hans">请求体，必须是 <see cref="ISidebarRequest"/>。</para>
		/// <para xml:lang="zh-Hant">要求主體，必須是 <see cref="ISidebarRequest"/>。</para>
		/// </param>
		/// <returns><c>true</c> if the request was sent successfully; otherwise, <c>false</c>.
		/// <para xml:lang="zh-Hans">如果请求发送成功则返回 <c>true</c>；否则返回 <c>false</c>。</para>
		/// <para xml:lang="zh-Hant">如果要求傳送成功則傳回 <c>true</c>；否則傳回 <c>false</c>。</para>
		/// </returns>
		bool Request (ISidebarRequest request);
		/// <summary>
		/// Sends a request to a specified target, which can be the Sidebar or another tile.
		/// <para xml:lang="zh-Hans">向指定目标发送请求，目标可以是边栏或其他磁贴。</para>
		/// <para xml:lang="zh-Hant">向指定目的地傳送要求，目的地可以是邊欄或其他磁貼。</para>
		/// </summary>
		/// <param name="request">The request body, which must be an <see cref="ITileRequest"/>.
		/// <para xml:lang="zh-Hans">请求体，必须是 <see cref="ITileRequest"/>。</para>
		/// <para xml:lang="zh-Hant">要求主體，必須是 <see cref="ITileRequest"/>。</para>
		/// </param>
		/// <returns><c>true</c> if the request was sent successfully; otherwise, <c>false</c>.
		/// <para xml:lang="zh-Hans">如果请求发送成功则返回 <c>true</c>；否则返回 <c>false</c>。</para>
		/// <para xml:lang="zh-Hant">如果要求傳送成功則傳回 <c>true</c>；否則傳回 <c>false</c>。</para>
		/// </returns>
		bool Communicate (ITileRequest request);
		/// <summary>
		/// Sends a response to the Sidebar or another tile.
		/// <para xml:lang="zh-Hans">向边栏或其他磁贴发送响应。</para>
		/// <para xml:lang="zh-Hant">向邊欄或其他磁貼傳送回應。</para>
		/// </summary>
		/// <param name="resp">The response body, which must be an <see cref="ITileResponse"/>.
		/// <para xml:lang="zh-Hans">响应体，必须是 <see cref="ITileResponse"/>。</para>
		/// <para xml:lang="zh-Hant">回應主體，必須是 <see cref="ITileResponse"/>。</para>
		/// </param>
		/// <returns><c>true</c> if the response was sent successfully; otherwise, <c>false</c>.
		/// <para xml:lang="zh-Hans">如果响应发送成功则返回 <c>true</c>；否则返回 <c>false</c>。</para>
		/// <para xml:lang="zh-Hant">如果回應傳送成功則傳回 <c>true</c>；否則傳回 <c>false</c>。</para>
		/// </returns>
		bool Response (ITileResponse resp);
		/// <summary>
		/// Gets the read-only configuration of the Sidebar.
		/// <para xml:lang="zh-Hans">获取边栏的只读配置。</para>
		/// <para xml:lang="zh-Hant">取得邊欄的唯讀設定。</para>
		/// </summary>
		ISidebarConfig Config { get; }
	}
