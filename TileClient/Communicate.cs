	[ComVisible (true)]
	public interface ITileRequest
	{
		/// <summary>
		/// Gets the unique identifier of the request, generated automatically when the request is created.
		/// <para xml:lang="zh-Hans">获取请求的唯一标识符，在创建请求时自动生成。</para>
		/// <para xml:lang="zh-Hant">取得要求的唯一識別碼，在建立要求時自動產生。</para>
		/// </summary>
		string RequestId { get; }
		/// <summary>
		/// Gets or sets the name of the request, which identifies the operation to perform.
		/// <para xml:lang="zh-Hans">获取或设置请求的名称，用于标识要执行的操作。</para>
		/// <para xml:lang="zh-Hant">取得或設定要求的名稱，用於識別要執行的作業。</para>
		/// </summary>
		string RequestName { get; }
