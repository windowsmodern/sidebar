		/// <summary>
		/// Gets the target of the response. It is copied from the request source.
		/// <para xml:lang="zh-Hans">获取响应的目标。该值从请求来源复制而来。</para>
		/// <para xml:lang="zh-Hant">取得回應的目的地。該值從要求來源複製而來。</para>
		/// </summary>
		public string ResponseTarget { get; }
		/// <summary>
		/// Gets or sets the name of the response, which identifies the result or action.
		/// <para xml:lang="zh-Hans">获取或设置响应的名称，用于标识结果或操作。</para>
		/// <para xml:lang="zh-Hant">取得或設定回應的名稱，用於識別結果或作業。</para>
		/// </summary>
		public string ResponseName { get; set; }
		/// <summary>
		/// Gets auxiliary data used only by the tile itself; it is copied from the request.
		/// <para xml:lang="zh-Hans">获取仅供磁贴自身使用的辅助数据；该值从请求复制而来。</para>
