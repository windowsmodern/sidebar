		/// Gets the user model ID of the tile or component that sent the request.
		/// <para xml:lang="zh-Hans">获取发送请求的磁贴或组件的用户模型 ID。</para>
		/// <para xml:lang="zh-Hant">取得傳送要求的磁貼或元件的使用者模型 ID。</para>
		/// </summary>
		string RequestSource { get; }
		/// <summary>
		/// Gets or sets the target of the request, such as "Sidebar" or the user model ID of another tile.
